def test_embedding_dimension_mismatch_is_detected():
    from app.rag.embeddings import EmbeddingError, EmbeddingService

    class BadProvider:
        name = "bad"
        embed_model = "bad-model"
        embedding_dim = 1024

        def embed(self, text):
            return [0.0] * 768

    service = EmbeddingService(provider=BadProvider())
    with pytest.raises(EmbeddingError):
        service.embed("hello world")


def test_embedding_service_reports_dimension():
    from app.rag.embeddings import get_embedding_service

    assert get_embedding_service().dimension == 1024


